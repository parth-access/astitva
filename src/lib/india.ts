/**
 * An Indian mobile number as its 10 digits, from however it was typed
 * ("+91 98123 45678", "098123-45678"). Null if it isn't one.
 */
export function normaliseMobile(input: string): string | null {
  let digits = input.replace(/\D/g, "");
  if (digits.length === 12 && digits.startsWith("91")) digits = digits.slice(2);
  else if (digits.length === 11 && digits.startsWith("0")) digits = digits.slice(1);
  return /^[6-9]\d{9}$/.test(digits) ? digits : null;
}

/** "+91 98123 45678". */
export function formatMobile(digits: string): string {
  return /^\d{10}$/.test(digits) ? `+91 ${digits.slice(0, 5)} ${digits.slice(5)}` : digits;
}

/** Six digits, not starting with 0. */
export const PINCODE_PATTERN = /^[1-9]\d{5}$/;
